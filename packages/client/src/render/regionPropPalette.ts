import type { RegionAssetCategory } from "@rustcraft/shared";

/** Curated, prefix-grouped organisation of the real nature/building asset
 *  directories for the region editor's asset palette (parallels
 *  dungeonPropPalette.ts's role for the dungeon editor). `category` records
 *  which real directory under assets/models/ each group's files live under
 *  (foliage/, buildings/, props/), since the loader needs the right path
 *  prefix and a RegionAsset can't infer it from the filename alone the way
 *  the dungeon editor's props-only palette could. */
export interface RegionPropPaletteGroup {
  label: string;
  category: RegionAssetCategory;
  models: string[];
  /** Optional pack override; otherwise inferred from label / model path. */
  pack?: string;
}

export const REGION_ASSET_DIR: Record<RegionAssetCategory, string> = {
  building: "buildings",
  foliage: "foliage",
  prop: "props",
};

export interface RegionPaletteAsset {
  model: string;
  category: RegionAssetCategory;
  group: string;
  pack: string;
}

