export function regionAssetDisplayName(model: string): string {
  const base = model.split("/").pop() ?? model;
  return base.replace(/\.(gltf|glb)$/i, "");
}

export function regionAssetUrl(category: RegionAssetCategory, model: string): string {
  return `/assets/models/${REGION_ASSET_DIR[category]}/${model}`;
}

export function flattenRegionPalette(
  groups: RegionPropPaletteGroup[] = REGION_PROP_PALETTE,
): RegionPaletteAsset[] {
  const out: RegionPaletteAsset[] = [];
  for (const g of groups) {
    const pack = regionGroupPack(g);
    for (const model of g.models) {
      out.push({ model, category: g.category, group: g.label, pack });
    }
  }
  return out;
}
