/** Infer asset pack from group label or first model path. */
export function regionPackForGroup(label: string, models: string[] = []): string {
  if (label.startsWith("FV ·")) return "Fantastic Village";
  if (label.startsWith("FL ·")) return "Free Low Poly";
  if (label.startsWith("CP ·") || label === "Castle Ruins") return "Castle Pack";
  if (label.startsWith("KH ·")) return "KayKit Hexagon";
  if (label.startsWith("MV ·")) return "Medieval Village";
  if (label.startsWith("SN ·")) return "Stylized Nature";
  const sample = models[0] ?? "";
  if (sample.includes("fantastic_village/")) return "Fantastic Village";
  if (sample.includes("free_lowpoly/")) return "Free Low Poly";
  if (sample.includes("castle_pack/") || sample.includes("castle_ruins/")) return "Castle Pack";
  if (sample.includes("kaykit_hexagon/")) return "KayKit Hexagon";
  if (sample.includes("medieval_village/")) return "Medieval Village";
  if (sample.includes("stylized_nature/")) return "Stylized Nature";
  return "Core";
}

export function regionGroupPack(group: RegionPropPaletteGroup): string {
  return group.pack ?? regionPackForGroup(group.label, group.models);
}
